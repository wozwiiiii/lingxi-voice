"""Provider 异常分类：瞬时不可用 vs 内容错误。

继承 ValueError 是刻意的契约兼容决策：``tts_service.py`` 的同步链路把
``ValueError`` 映射为 503（``except ValueError``），把其余异常映射为 502
并计入熔断失败。新增子类后该映射行为不变——老调用方的状态码语义零回归，
同时调用方又能通过 ``isinstance`` 精确区分两类错误。

为什么要区分：
    "供应商 5xx / 限流 / 余额不足" 和 "用户提交的内容不合法" 的处置完全
    不同：前者值得重试、且应计入熔断计数（供应商的锅）；后者重试没有意义、
    也不该污染熔断计数（不是供应商的锅，熔断打开只会让其他用户陪葬）。
    旧代码把两者都揉进裸 ``ValueError``，调用方无从分辨。
"""


class ProviderUnavailableError(ValueError):
    """供应商瞬时不可用：限流(429)、余额不足(402)、上游 5xx、连接故障。

    可重试；应计入熔断失败计数。
    """


class ContentError(ValueError):
    """内容/参数错误：文本超长、参数不合法、格式不支持等。

    重试无意义；不应计入熔断失败计数。
    """
